"""Write RESULTS.md and DATA_QUALITY.md from committed result files only."""
import json
from pathlib import Path
import numpy as np
import pandas as pd

m = json.load(open("results/metrics.json"))
feats = pd.read_csv("results/features.csv")
q = pd.read_csv("results/quality.csv")
fl = pd.read_csv("results/fetch_log.csv")
mc = json.load(open("results/matlab_check.json")) if Path("results/matlab_check.json").exists() else None
f = lambda v: "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.2f}"
ci = lambda c: f"[{f(c[0])}, {f(c[1])}]" if c and c[0] is not None else "n/a"

L = ["# Results", "",
     "Research prototype on open ICU data (MIMIC-III Waveform Database, matched subset), not a medical device. "
     "No clinical claim. Generated by `scripts/make_results.py` from `results/metrics.json`.", "",
     f"- Patients: **{m['n_patients']}**, 60 s windows: **{m['n_windows']}**, windows with mean ICP > 20 mmHg: **{m['pct_windows_icp_gt20']:.1f}%**",
     f"- Validation: {m['validation']}", "",
     "## Mean ICP per window (regression), MAE in mmHg", "",
     "| Model | Held-out MAE | 95% CI (patients) | Training MAE |", "|---|---|---|---|"]
for k, v in m["regression"].items():
    L.append(f"| {k} | {f(v['mae_heldout'])} | {ci(v['mae_heldout_ci95'])} | {f(v['mae_training'])} |")
for key, title in (("classification_icp_gt20", "ICP > 20 mmHg"), ("classification_icp_gt22", "ICP > 22 mmHg (sensitivity check)")):
    L += ["", f"## Intracranial hypertension, {title}: AUROC (pooled out-of-patient predictions)", "",
          "| Model | Held-out AUROC | 95% CI (patients) | Training AUROC |", "|---|---|---|---|"]
    for k, v in m[key].items():
        L.append(f"| {k} | {f(v['auroc_heldout'])} | {ci(v['auroc_heldout_ci95'])} | {f(v['auroc_training'])} |")
p = m["ptt_direction"]
L += ["", "## Pulse transit time direction", "",
      f"- Windows with a valid PTT: {p['n_windows_with_ptt']}",
      f"- Pooled Spearman rho (PTT vs mean ICP): {f(p['pooled_spearman_rho'])}",
      f"- Median within-patient rho: {f(p['median_within_patient_rho'])}; patients with negative rho: "
      f"{p['n_patients_negative_rho']} of {len(p['within_patient_spearman_rho'])}",
      "- Expected direction from physiology (FEATURES.md): negative (higher ICP → Cushing response → shorter PTT).",
      "", "Per-patient rho: " + ", ".join(f"{s} {f(r)}" for s, r in p["within_patient_spearman_rho"].items())]
if "cnn_train_seconds" in m:
    L += ["", f"CNN (src/cnn.py) total LOPO training time: {m['cnn_train_seconds']:.0f} s on CPU."]
L += ["", "## MATLAB-syntax cross-check", ""]
if mc:
    L += [f"- Engine: {mc['engine']} (MATLAB R2026b run: `results/matlab_online_check.json`)",
          f"- {mc['windows']} raw PPG windows; filtered signal max |diff| vs Python: {mc['filtered_max_abs_diff']:.2e} (whole window), "
          f"{mc['filtered_max_abs_diff_interior']:.2e} (interior, 2 s trimmed each end). Python uses MATLAB's filtfilt pad length 3*(nfilt-1); with SciPy's default pad the edge difference was 0.27 (z-units, at the window edges)",
          f"- Systolic peaks: Python {mc['peaks_python']}, Octave {mc['peaks_matlab']}, identical sample index {mc['peaks_identical_index']}"]
else:
    L.append("- Octave check skipped.")
mf = feats[feats.subject.isin(m["patients"])]
pos = mf.groupby("subject").ich.sum()
pos = pos[pos > 0].sort_values(ascending=False)
L += ["", "## Reading these numbers", "",
      f"- Only {int(mf.ich.sum())} of {len(mf)} windows are > 20 mmHg, from {len(pos)} of {m['n_patients']} patients ("
      + ", ".join(f"{s} {int(n)}" for s, n in pos.items()) + "). The hypertension AUROC therefore rests on very few patients.",
      "- The predict-the-mean baseline scores AUROC well below 0.5 by construction: leaving out a high-ICP patient lowers the training prevalence that is predicted for exactly that patient. Pooled AUROC across patients also rewards ranking patients against each other, not only tracking ICP within a patient.",
      "- Regression: no model beats predict-the-mean on held-out patients (lower MAE is better). Training MAE far below held-out MAE (gradient boosting) means the fit is patient-specific.",
      f"- n = {m['n_patients']} patients: confidence intervals are wide and one patient can swing the pooled metric.",
      "- ICP level differs mostly **between** patients; leave-one-patient-out asks the model to guess a new patient's level from finger PPG alone, which is the hard, honest version of the task.",
      "- Training numbers beside held-out numbers show how much of the fit is patient-specific."]
Path("RESULTS.md").write_text("\n".join(L) + "\n")

# DATA_QUALITY.md
kept = q[q.kept]
D = ["# Data quality and data card", "",
     "Generated by `scripts/make_results.py` from `results/fetch_log.csv`, `results/quality.csv`, `results/features.csv`.", "",
     "- Source: MIMIC-III Waveform Database Matched Subset v1.0, PhysioNet (`mimic3wdb/1.0/matched`), open access.",
     "- License as stated on PhysioNet: **Open Data Commons Open Database License v1.0 (ODbL)** (`LICENSE.txt` in the database).",
     "- Signals used: `PLETH` (finger PPG), `II` (ECG lead II), `ICP` (invasive ICP, ground truth), 125 Hz.",
     "- Record search: `scripts/find_records.py` scanned layout headers of matched records; hits in `results/candidates.csv`.",
     f"- Subjects with an ICP + PLETH + II record found: {fl.subject.nunique()}; subjects where those three signals co-occur in a segment for ≥ 10 windows: {(fl.windows >= 10).sum()}.",
     "- Per subject at most 2 h, taken as 10-minute chunks spread evenly over all eligible segments, cut into 60 s windows.", "",
     "## Window rejection", "", "| Reason | Windows |", "|---|---|"]
for r, n in q.reason.value_counts().items():
    D.append(f"| {r} | {n} |")
D += ["", f"Kept {len(kept)} of {len(q)} windows ({100*len(kept)/len(q):.1f}%). Kept-window hours: {len(feats)/60:.1f}.", "",
      "## Per subject (subjects with ≥ 1 fetched window)", "",
      "| Subject | Fetched windows | Kept windows | Mean ICP (mmHg) | % windows ICP > 20 | PTT valid |", "|---|---|---|---|---|---|"]
for s, g in q.groupby("subject"):
    fs_ = feats[feats.subject == s]
    D.append(f"| {s} | {len(g)} | {len(fs_)} | {f(fs_.icp_mean.mean()) if len(fs_) else 'n/a'} | "
             f"{f(100*fs_.ich.mean()) if len(fs_) else 'n/a'} | {int(fs_.ptt_ms.notna().sum()) if len(fs_) else 0} |")
d = feats.icp_mean.describe(percentiles=[.1, .25, .5, .75, .9])
D += ["", "## ICP distribution (kept windows, mean ICP per 60 s, mmHg)", "",
      "| n | mean | sd | min | p10 | p25 | median | p75 | p90 | max |", "|---|---|---|---|---|---|---|---|---|---|",
      "| " + " | ".join([str(int(d['count']))] + [f(d[k]) for k in ['mean', 'std', 'min', '10%', '25%', '50%', '75%', '90%', 'max']]) + " |",
      "", f"Windows with mean ICP > 20 mmHg: {100*feats.ich.mean():.1f}%; > 22 mmHg: {100*feats.ich22.mean():.1f}%.", "",
      "## Modeling set (patients with >= 10 kept windows; used by `scripts/run_models.py`)", ""]
ms = feats[feats.subject.isin(m["patients"])]
dm = ms.icp_mean.describe(percentiles=[.1, .25, .5, .75, .9])
D += [f"- Patients: {ms.subject.nunique()} ({', '.join(m['patients'])}); windows: {len(ms)}; hours: {len(ms)/60:.1f}", "",
      "| n | mean | sd | min | p10 | p25 | median | p75 | p90 | max |", "|---|---|---|---|---|---|---|---|---|---|",
      "| " + " | ".join([str(int(dm['count']))] + [f(dm[k]) for k in ['mean', 'std', 'min', '10%', '25%', '50%', '75%', '90%', 'max']]) + " |",
      "", f"Windows with mean ICP > 20 mmHg: {100*ms.ich.mean():.1f}% ({int(ms.ich.sum())}); > 22 mmHg: {100*ms.ich22.mean():.1f}% ({int(ms.ich22.sum())}).", "",
      "## Rules (src/preprocess.py)", "",
      "- Reject: > 1% NaN in any signal; flat PPG/ECG; PPG clipped (> 5% samples at window max or min); mean ICP outside −5…60 mmHg or any sample outside −20…100; ICP SD < 0.05 mmHg (clamped EVD / transducer off); < 10 beats with template correlation ≥ 0.9.",
      "- Filters: PPG 0.5–8 Hz, ECG 5–30 Hz, 4th-order Butterworth, zero-phase."]
Path("DATA_QUALITY.md").write_text("\n".join(D) + "\n")
print("wrote RESULTS.md, DATA_QUALITY.md")
